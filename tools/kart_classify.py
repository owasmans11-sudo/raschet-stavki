def classify(name, text):
    fn = norm(name)[11:]  # без даты в начале
    t = norm(text)
    head = t[:1200]
    readable = len(re.findall(r'[а-я]{3,}', t)) >= 8
    src = 'text'
    if re.match(r'.{0,30}реквизиты', head):
        return COMPANY, 'head'
    # 0) счёт/УПД в самой шапке важнее упоминания «по заявке»
    if T_BUH.search(head[:300]) and not re.search(r'договор[\s-]*заявк', head[:300]):
        return BUH, 'head'
    # 1) заявки — главная категория
    if T_ZAY.search(head) or (F_ZAY.search(fn) and not T_BUH.search(head[:300])):
        return ZAYAVKA, 'zay'
    # 2) по шапке текста
    for rx, cat in ((T_POST, POST), (T_BUH, BUH), (T_TR, TRANSPORT), (T_VEH, DRIVER), (T_EGR, COMPANY), (T_DOG, DOGOVOR), (T_DRV, DRIVER), (T_COMP, COMPANY)):
        if rx.search(head):
            return cat, 'head'
    # 3) по имени файла
    for rx, cat in ((F_POST, POST), (F_BUH, BUH), (F_TR, TRANSPORT), (F_DRV, DRIVER), (F_COMP, COMPANY), (F_DOG, DOGOVOR)):
        if rx.search(fn):
            return cat, 'name'
    # 4) заявка без заголовка: погрузка/выгрузка/ставка в тексте (минимум 2 признака)
    if len(set(m.group(0)[:6] for m in T_ZAY_BODY.finditer(t))) >= 2:
        return ZAYAVKA, 'body'
    # 5) по всему тексту
    if re.search(r'наличную оплату за перевозку|в случае его хищения|ответственность перевозчика за|отказ\w* заказчика от перевозки|предоставления исполнителем транспортного|дополнительного пробега|вес груза не должен превышать', t):
        return ZAYAVKA, 'page2'
    if re.search(r'грузополучател|грузоотправител', t):
        return TRANSPORT, 'full'
    for rx, cat in ((T_POST, POST), (T_BUH, BUH), (T_TR, TRANSPORT), (T_VEH, DRIVER), (T_EGR, COMPANY), (T_DRV, DRIVER), (T_COMP, COMPANY), (T_DOG, DOGOVOR)):
        if rx.search(t):
            return cat, 'full'
    if re.search(r'\bинн\b', t) and re.search(r'адрес|огрн|р/с|расч', t) and not re.search(r'претензи|сертификат|предложени|возврат|требовани|fwd|от:|письм|компания с', t + ' ' + fn):
        return COMPANY, 'inn'
    if T_VEH.search(t):
        return DRIVER, 'full'
    return (OTHER, 'other') if readable else (UNREAD, 'unread')

