# Взято из чата «Excel заявки с клиентами + УПД» (24.10.2026) для картотеки документов — tools/build_kartoteka.py
"""Роль ВЛ / ИП Шерстов в заявке.
client  — заявка с клиентом (ВЛ исполнитель/перевозчик) — в таблицу;
carrier — заявка ВЛ своему перевозчику (ВЛ заказчик) — не в таблицу;
none    — ВЛ не упоминается; ?  — не ясно."""
import re

VLN = r'(?:восточн\S{0,3}\s*логист\S*|vostok\S*|шерстов\S*(?:\s+а\.?\s*в\.?|\s+андре\S*\s+витал\S*)?)'
VL = re.compile(VLN + r'|3812166710|381100987938')
ORGP = r'(?:ооо|ип|оао|ао|общество с ограниченной ответственностью|индивидуальный предприниматель)?\s*[«"“„(]*\s*'
CARRIER = r'(?:перевозчик\S*(?:-экспедитор)?|исполнител\S*|экспедитор\S*|фрахтовщик\S*)'
CLIENT = r'(?:заказчик\S*|клиент\S*|фрахтовател\S*)'

def norm(s):
    return re.sub(r'\s+', ' ', s.lower().replace('ё', 'е'))

def role(text):
    t = norm(text)
    if not VL.search(t):
        return 'none', 'ВЛ не упоминается'
    if re.search(r'об организац\S* пер\S*возок', t[:600]) and VL.search(t[:300]):
        return 'carrier', 'бланк ВЛ перевозчику'
    # тот же бланк ВЛ, когда OCR испортил заголовок: шапка ВЛ + «1. ЗАГРУЗКА 2. РАЗГРУЗКА»
    if re.search(r'vost|381216|3812166|1253800008', t[:300]) and re.search(r'1\.?\s*з\S{0,2}гру\S*.{0,40}2\.?\s*р\S{0,2}згру', t[:700]):
        return 'carrier', 'бланк ВЛ перевозчику (по шапке)'
    if 'фрахтован' in t[:800] and VL.search(t[:300]):
        return 'client', 'заказ-наряд ВЛ клиенту'
    score = 0
    # «Перевозчик: ООО Восточная Логистика» / «Заказчик: ООО Восточная Логистика»
    for m in re.finditer(rf'\b({CARRIER}|{CLIENT})\s*[:/–-]?\s*{ORGP}{VLN}', t):
        score += 2 if re.match(CARRIER, m.group(1)) else -2
    # «ООО Восточная Логистика, именуемое в дальнейшем Перевозчик»
    for m in re.finditer(rf'{VLN}.{{0,120}}?именуем\S*\s*(?:в дальнейшем|далее)?\s*\W{{0,3}}\s*({CARRIER}|{CLIENT})', t):
        score += 3 if re.match(CARRIER, m.group(1)) else -3
    # подпись: «Перевозчик ... ИП Шерстов А.В.» в двух колонках — слабый признак
    if re.search(r'оплата будет от фирмы|на фирму ип шерстов|на р/с исполнителя', t):
        score += 1
    if score > 0:
        return 'client', f'счёт {score}'
    if score < 0:
        return 'carrier', f'счёт {score}'
    return '?', 'нет явной метки'
